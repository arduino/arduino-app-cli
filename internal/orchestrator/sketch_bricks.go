// SystemBricks are the bricks of the data dir. Every app can use them.
func SystemBricks(cfg config.Configuration) []bricksindex.Brick {
	dataDir := cfg.DataDir()
	if dataDir == nil {
		return nil
	}
	bricks := app.LoadBricksFromFolder(dataDir.Join("bricks"))
	for i := range bricks {
		bricks[i].Source = "System"
	}
	return bricks
}

// appHasSketchToBuild is true when the app has a sketch, or a brick of the app brings MCU code.
func appHasSketchToBuild(arduinoApp app.ArduinoApp, index *bricksindex.BricksIndex) bool {
	if _, hasSketch := arduinoApp.GetSketchPath(); hasSketch {
		return true
	}
	return len(bricksWithSketchLibrary(arduinoApp, index)) > 0
}

// bricksWithSketchLibrary returns the bricks of the app that bring MCU code.
func bricksWithSketchLibrary(arduinoApp app.ArduinoApp, index *bricksindex.BricksIndex) []bricksindex.Brick {
	bricks := []bricksindex.Brick{}
	for _, declared := range arduinoApp.Descriptor.Bricks {
		brick, found := index.FindBrickByID(declared.ID)
		if !found {
			continue
		}
		if _, hasLibrary := brick.GetSketchLibrary(); hasLibrary {
			bricks = append(bricks, *brick)
		}
	}
	return bricks
}

// stageSketch returns the sketch to compile. With bricks, it is a copy of the app
// sketch, or a generated one, plus a file that starts every brick.
func stageSketch(arduinoApp app.ArduinoApp, bricks []bricksindex.Brick) (*paths.Path, error) {
	sketchPath, hasSketch := arduinoApp.GetSketchPath()
	if len(bricks) == 0 {
		if !hasSketch {
			return nil, errors.New("the app has no sketch, and no brick brings one")
		}
		return sketchPath, nil
	}

	// arduino-cli reads the main file name from the folder name.
	stageRoot := arduinoApp.SketchBuildPath().Parent().Join("staged")
	stageDir := stageRoot.Join("sketch")
	if err := stageRoot.RemoveAll(); err != nil {
		return nil, fmt.Errorf("failed to clean the staged sketch: %w", err)
	}
	if err := stageRoot.MkdirAll(); err != nil {
		return nil, fmt.Errorf("failed to create the staged sketch folder: %w", err)
	}

	if hasSketch {
		if err := sketchPath.CopyDirTo(stageDir); err != nil {
			return nil, fmt.Errorf("failed to copy the app sketch: %w", err)
		}
	} else {
		if err := stageDir.MkdirAll(); err != nil {
			return nil, fmt.Errorf("failed to create the staged sketch folder: %w", err)
		}
		// The bricks wait for the sketch to start the Bridge.
		entrySketch := `// Generated by arduino-app-cli: the app has no sketch of its own.

#include <Arduino_RouterBridge.h>

void setup() {
    Bridge.begin();
}

void loop() {
    delay(100);
}
`
		if err := stageDir.Join("sketch.ino").WriteFile([]byte(entrySketch)); err != nil {
			return nil, fmt.Errorf("failed to write the generated sketch: %w", err)
		}
		sketchProject := `# Generated by arduino-app-cli: the app has no sketch of its own.
profiles:
  default:
    platforms:
      - platform: arduino:zephyr
    libraries: []
default_profile: default
`
		if err := stageDir.Join("sketch.yaml").WriteFile([]byte(sketchProject)); err != nil {
			return nil, fmt.Errorf("failed to write the generated sketch project: %w", err)
		}
	}

	init, err := brickInitSource(bricks)
	if err != nil {
		return nil, err
	}
	if err := stageDir.Join("app_bricks.cpp").WriteFile([]byte(init)); err != nil {
		return nil, fmt.Errorf("failed to write the brick init file: %w", err)
	}
	return stageDir, nil
}

// brickSketchLibraries returns the brick libraries with the brick API library, and
// the depends= entries of the brick libraries.
func brickSketchLibraries(bricks []bricksindex.Brick, cfg config.Configuration) ([]*paths.Path, []LibraryReleaseID, error) {
	if len(bricks) == 0 {
		return nil, nil, nil
	}
	const apiLibraryName = "ArduinoAppBricks"
	dataDir := cfg.DataDir()
	if dataDir == nil {
		return nil, nil, errors.New("the bricks of the app bring a sketch: no data dir is configured")
	}
	apiLibrary := dataDir.Join("sketch-libraries", apiLibraryName)
	if apiLibrary.NotExist() {
		return nil, nil, fmt.Errorf("the bricks of the app bring a sketch: %s is not installed at %s", apiLibraryName, apiLibrary)
	}

	libraries := []*paths.Path{apiLibrary}
	dependencies := []LibraryReleaseID{}
	for _, brick := range bricks {
		libDir, hasLibrary := brick.GetSketchLibrary()
		if !hasLibrary {
			continue
		}
		libraries = append(libraries, libDir)
		for _, dependency := range libraryDependencies(libDir.Join("library.properties")) {
			// The API library is added by path.
			if dependency.Name == apiLibraryName {
				continue
			}
			if !slices.Contains(dependencies, dependency) {
				dependencies = append(dependencies, dependency)
			}
		}
	}
	return libraries, dependencies, nil
}

// addBrickLibrariesToProfile adds the brick libraries by path, and their
// dependencies from the index, to the profile of the staged sketch.
func addBrickLibrariesToProfile(
	ctx context.Context,
	sketchPath *paths.Path,
	libraries []*paths.Path,
	dependencies []LibraryReleaseID,
	w io.Writer,
) error {
	if len(libraries) == 0 && len(dependencies) == 0 {
		return nil
	}

	// The compile instance reads the profile at init, so this one loads no profile.
	srv, inst, err := initializeArduinoCli(ctx, nil, w)
	if err != nil {
		return err
	}
	defer func() { _, _ = srv.Destroy(ctx, &rpc.DestroyRequest{Instance: inst}) }()

	for _, library := range libraries {
		fmt.Fprintf(w, "The sketch profile gets %s\n", library)
	}
	for _, dependency := range dependencies {
		fmt.Fprintf(w, "The sketch profile gets %s, a dependency of a brick library\n", dependency.Name)
	}
	for _, library := range libraries {
		reference := &rpc.ProfileLibraryReference{
			Library: &rpc.ProfileLibraryReference_LocalLibrary_{
				LocalLibrary: &rpc.ProfileLibraryReference_LocalLibrary{Path: library.String()},
			},
		}
		if err := addProfileLibrary(ctx, srv, inst, sketchPath, reference, false); err != nil {
			return fmt.Errorf("failed to add the library %s: %w", library, err)
		}
	}
	for _, dependency := range dependencies {
		reference := &rpc.ProfileLibraryReference{
			Library: &rpc.ProfileLibraryReference_IndexLibrary_{
				IndexLibrary: &rpc.ProfileLibraryReference_IndexLibrary{
					Name:    dependency.Name,
					Version: dependency.Version,
				},
			},
		}
		if err := addProfileLibrary(ctx, srv, inst, sketchPath, reference, true); err != nil {
			// A dependency the sketch already names is not an error.
			slog.Warn("cannot add a brick dependency to the sketch profile",
				slog.String("library", dependency.Name), slog.String("error", err.Error()))
		}
	}
	return nil
}

// brickInitSource renders the file that starts the bricks: one include and one setup call per brick.
func brickInitSource(bricks []bricksindex.Brick) (string, error) {
	type brickEntry struct {
		Header    string
		Namespace string
	}
	entries := []brickEntry{}
	for _, brick := range bricks {
		libDir, _ := brick.GetSketchLibrary()
		name, err := libraryProperty(libDir.Join("library.properties"), "name")
		if err != nil {
			return "", fmt.Errorf("the sketch library of brick %q: %w", brick.ID, err)
		}
		header := name + ".h"
		if libDir.Join("src", header).NotExist() {
			return "", fmt.Errorf("the sketch library of brick %q: header %q not found in src", brick.ID, header)
		}
		entries = append(entries, brickEntry{Header: header, Namespace: brick.ID})
	}

	// The static initializer only creates the thread that waits for the Bridge.
	initFile := template.Must(template.New("app_bricks.cpp").Parse(
		`// Generated by arduino-app-cli. Do not edit.

#include <Arduino.h>
#include <ArduinoAppBricks.h>
{{range .}}#include <{{.Header}}>
{{end}}
static void startBricks() {
{{- range .}}
	{{.Namespace}}::setup();
{{- end}}
}

[[maybe_unused]] static const int bricksStarted = arduino_app_bricks::begin(startBricks);
`))
	var source strings.Builder
	if err := initFile.Execute(&source, entries); err != nil {
		return "", err
	}
	return source.String(), nil
}

func addProfileLibrary(
	ctx context.Context,
	srv rpc.ArduinoCoreServiceServer,
	inst *rpc.Instance,
	sketchPath *paths.Path,
	reference *rpc.ProfileLibraryReference,
	withDependencies bool,
) error {
	_, err := srv.ProfileLibAdd(ctx, &rpc.ProfileLibAddRequest{
		Instance:        inst,
		SketchPath:      sketchPath.String(),
		Library:         reference,
		AddDependencies: &withDependencies,
	})
	return err
}

// libraryDependencies reads the depends field of a library.properties file. It
// keeps a version only when the constraint names exactly one version.
func libraryDependencies(propertiesFile *paths.Path) []LibraryReleaseID {
	depends, err := libraryProperty(propertiesFile, "depends")
	if err != nil || depends == "" {
		return nil
	}
	dependencies := []LibraryReleaseID{}
	for dependency := range strings.SplitSeq(depends, ",") {
		name, constraint, hasConstraint := strings.Cut(strings.TrimSpace(dependency), "(")
		library := LibraryReleaseID{Name: strings.TrimSpace(name)}
		if version := strings.TrimSuffix(strings.TrimSpace(constraint), ")"); hasConstraint && !strings.ContainsAny(version, "<>=^~") {
			library.Version = version
		}
		if library.Name != "" {
			dependencies = append(dependencies, library)
		}
	}
	return dependencies
}

func libraryProperty(propertiesFile *paths.Path, key string) (string, error) {
	content, err := propertiesFile.ReadFile()
	if err != nil {
		return "", err
	}
	for line := range strings.SplitSeq(string(content), "\n") {
		if value, found := strings.CutPrefix(strings.TrimSpace(line), key+"="); found {
			return strings.TrimSpace(value), nil
		}
	}
	return "", nil
}
